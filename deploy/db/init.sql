CREATE TABLE events
(
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         text NOT NULL,
    location      text NOT NULL,
    description   text,
    photo_file_id text,
    starts_at     timestamptz,
    ends_at       timestamptz,
    capacity      integer CHECK (capacity > 0), -- NULL means unlimited.
    CHECK (ends_at > starts_at)
);

CREATE TABLE users
(
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firstname   text   NOT NULL,
    lastname    text   NOT NULL,
    surname     text,
    tg_username text,
    tg_id       bigint NOT NULL UNIQUE,
    role        text   NOT NULL DEFAULT 'user'
);

CREATE TABLE tags
(
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

CREATE TABLE event_registrations
(
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL,
    user_id  integer NOT NULL,

    UNIQUE (event_id, user_id),

    FOREIGN KEY (event_id) REFERENCES events (id)
        ON DELETE NO ACTION ON UPDATE NO ACTION,

    FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE TABLE tags_to_events
(
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_id   integer,
    event_id integer,

    FOREIGN KEY (tag_id) REFERENCES tags (id)
        ON DELETE NO ACTION ON UPDATE NO ACTION,

    FOREIGN KEY (event_id) REFERENCES events (id)
        ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE INDEX IF NOT EXISTS event_registrations_user_event_idx
    ON event_registrations (user_id, event_id);
CREATE INDEX IF NOT EXISTS tags_to_events_tag_event_idx
    ON tags_to_events (tag_id, event_id);
CREATE INDEX IF NOT EXISTS events_starts_at_id_idx
    ON events (starts_at, id);
CREATE INDEX IF NOT EXISTS tags_to_events_event_tag_idx
    ON tags_to_events (event_id, tag_id);
